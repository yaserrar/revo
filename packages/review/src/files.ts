/** File filtering and size limits (spec 7.2 and 7.3). */
import {
  BUILT_IN_IGNORE_GLOBS,
  changedLineCount,
  createGlobMatcher,
  globError,
  REVIEW_LIMITS,
} from '@revo/shared';
import type { ChangedFile, SkippedFile } from './types';

/**
 * Built-in globs plus the repo's own. The repo's are checked again here (the
 * database may hold patterns saved before a rule existed): invalid ones are
 * left out. Matching is linear in pattern and path size, whatever the pattern.
 */
export function createIgnoreMatcher(extraGlobs: readonly string[] = []): (path: string) => boolean {
  return createGlobMatcher([...BUILT_IN_IGNORE_GLOBS, ...extraGlobs.filter((g) => globError(g) === null)]);
}

export type FilterResult = { reviewable: ChangedFile[]; skipped: SkippedFile[] };

/** A NUL byte never appears in text files: GitHub and git treat such files as binary. */
export function looksBinary(file: ChangedFile): boolean {
  if (!file.patch && file.newContent === undefined) return true;
  return file.newContent?.includes('\u0000') === true || file.patch?.includes('\u0000') === true;
}

const GENERATED_HEADER =
  /^\s*(?:\/\/|#|\/\*+|\*|<!--|--)\s*(?:@generated\b|.*\bcode generated\b.*\bdo not edit\b|.*\bthis file (?:is|was) (?:auto-?)?generated\b|.*\bauto-?generated\b.*\bdo not (?:edit|modify)\b)/i;

/** The first lines of the new version (or of the added lines when only a patch exists). */
function headLines(file: ChangedFile, count: number): string[] {
  if (file.newContent !== undefined) return file.newContent.split('\n', count);
  return (file.patch ?? '')
    .split('\n')
    .filter((l) => l.startsWith('+'))
    .slice(0, count)
    .map((l) => l.slice(1));
}

/** Generated by a tool, as declared in its header comment (`@generated`, "DO NOT EDIT"). */
export function looksGenerated(file: ChangedFile): boolean {
  return headLines(file, 5).some((line) => GENERATED_HEADER.test(line));
}

/** Minified or bundled: very long lines that no person writes or reviews. */
export function looksMinified(file: ChangedFile): boolean {
  const lines = headLines(file, 50).filter((l) => l.length > 0);
  if (lines.length === 0) return false;
  const longest = Math.max(...lines.map((l) => l.length));
  const average = lines.reduce((sum, l) => sum + l.length, 0) / lines.length;
  return longest > 2_000 && average > 300;
}

/**
 * Drops what is not worth a review (spec 7.2): built-in and repo ignore globs,
 * removed files, binaries, and files that are generated or minified even
 * though their path does not say so.
 */
export function filterFiles(
  files: readonly ChangedFile[],
  ignoreGlobs: readonly string[] = [],
): FilterResult {
  const isIgnored = createIgnoreMatcher(ignoreGlobs);
  const reviewable: ChangedFile[] = [];
  const skipped: SkippedFile[] = [];
  for (const file of files) {
    if (isIgnored(file.path)) skipped.push({ path: file.path, reason: 'ignored' });
    else if (file.status === 'removed') skipped.push({ path: file.path, reason: 'removed' });
    else if (looksBinary(file)) skipped.push({ path: file.path, reason: 'binary' });
    else if (looksGenerated(file) || looksMinified(file))
      skipped.push({ path: file.path, reason: 'ignored' });
    else reviewable.push(file);
  }
  return { reviewable, skipped };
}

const HIGH_RISK = [
  /(^|\/)(api|routes?|controllers?|handlers?|server|webhooks?)(\/|$)/i,
  /(^|\/)(auth|session|login|permissions?|acl|middleware|proxy)/i,
  /(^|\/)(payments?|billing|checkout|stripe|invoices?|pricing|orders?)/i,
  /(^|\/)(db|database|prisma|models?|repositories|migrations?|schema)/i,
  /\.(sql|prisma)$/i,
];
const TEST_FILE = /(^|\/)(__tests__|tests?|e2e|spec)(\/|$)|\.(test|spec)\.[a-z]+$/i;

/** 1 = API/auth/payments/database/migrations, 2 = other source, 3 = tests. */
export function riskTier(path: string): 1 | 2 | 3 {
  if (TEST_FILE.test(path)) return 3;
  return HIGH_RISK.some((re) => re.test(path)) ? 1 : 2;
}

export function fileChangedLines(file: ChangedFile): number {
  return file.patch ? changedLineCount(file.patch) : file.additions + file.deletions;
}

/** Changed by the commits pushed since Revo's last review of the PR. */
export function isRecent(file: ChangedFile): boolean {
  return file.sinceLastReview !== undefined;
}

/**
 * Review priority: files changed since the last review first (a new push is
 * always looked at, even on a PR above the size limits), then the riskiest
 * tier, then the most changed file.
 */
export function compareFilePriority(a: ChangedFile, b: ChangedFile): number {
  return (
    Number(isRecent(b)) - Number(isRecent(a)) ||
    riskTier(a.path) - riskTier(b.path) ||
    fileChangedLines(b) - fileChangedLines(a)
  );
}

export type SelectResult = { selected: ChangedFile[]; skipped: SkippedFile[]; note: string | null };

/**
 * Applies the size limits (REVIEW_LIMITS): above them, keeps files in review
 * priority (changed since the last review, then risk tier, then most changed)
 * until the limits are reached.
 */
export function selectFiles(
  files: readonly ChangedFile[],
  limits: { maxChangedLines: number; maxFiles: number } = REVIEW_LIMITS,
): SelectResult {
  const total = files.reduce((sum, f) => sum + fileChangedLines(f), 0);
  if (total <= limits.maxChangedLines && files.length <= limits.maxFiles) {
    return { selected: [...files], skipped: [], note: null };
  }
  const ordered = [...files].sort(compareFilePriority);
  const selected: ChangedFile[] = [];
  const skipped: SkippedFile[] = [];
  let lines = 0;
  for (const file of ordered) {
    const size = fileChangedLines(file);
    const fits =
      selected.length < limits.maxFiles && (lines + size <= limits.maxChangedLines || selected.length === 0);
    if (fits) {
      selected.push(file);
      lines += size;
    } else {
      skipped.push({ path: file.path, reason: 'size_limit' });
    }
  }
  return {
    selected,
    skipped,
    note: largePrNote(selected.length, files.length),
  };
}

/** The note shown in the comment when not every file was reviewed (spec 7.3). */
export function largePrNote(reviewed: number, total: number): string {
  return `Large PR: reviewed ${reviewed} of ${total} files.`;
}
