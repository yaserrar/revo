import { describe, expect, it } from 'vitest';
import { buildReviewContext } from '../src/context';
import { filterFiles, looksGenerated, looksMinified } from '../src/files';
import { estimateTokens } from '../src/tokens';
import type { ChangedFile } from '../src/types';

const lines = (n: number, tag: string) =>
  Array.from({ length: n }, (_, i) => `const ${tag}${i} = ${i};`).join('\n');

function file(path: string, total: number, status: ChangedFile['status'] = 'modified'): ChangedFile {
  return {
    path,
    status,
    patch: `@@ -3,1 +3,1 @@\n-old\n+const ${path.replace(/\W/g, '')}2 = 2;`,
    additions: 1,
    deletions: 1,
    newContent: lines(total, path.replace(/\W/g, '')),
  };
}

const pr = { title: 'Add things', body: 'Why it matters.' };

describe('buildReviewContext', () => {
  it('shows full small files, excerpts of large ones, riskiest first', () => {
    const ctx = buildReviewContext({
      pr,
      files: [file('src/util.ts', 20), file('src/api/orders.ts', 700)],
      related: [{ path: 'prisma/schema.prisma', content: 'model Order {}' }],
      budgetTokens: 100_000,
    });
    expect(ctx.files).toEqual([
      { path: 'src/api/orders.ts', mode: 'excerpt', truncated: false },
      { path: 'src/util.ts', mode: 'full', truncated: false },
    ]);
    expect(ctx.related).toEqual(['prisma/schema.prisma']);
    expect(ctx.droppedFiles).toEqual([]);
    expect(ctx.text).toContain('<title>Add things</title>');
    expect(ctx.text).toContain('priority="high"');
    expect(ctx.text).toContain('<excerpt lines="1-43">');
    expect(ctx.text.indexOf('src/api/orders.ts')).toBeLessThan(ctx.text.indexOf('src/util.ts'));
    expect(ctx.estimatedTokens).toBe(estimateTokens(ctx.text));
  });

  it('skips the patch of an added file shown in full', () => {
    const ctx = buildReviewContext({
      pr,
      files: [file('src/new.ts', 5, 'added')],
      related: [],
      budgetTokens: 50_000,
    });
    expect(ctx.text).not.toContain('<diff>');
    expect(ctx.text).toContain('<new_file lines="5">');
  });

  it('cuts related files first, then full files, then excerpts, then whole files', () => {
    const files = [file('src/api/a.ts', 400), file('src/b.ts', 400), file('test/c.test.ts', 400)];
    const related = [
      { path: 'r1.ts', content: lines(300, 'r1') },
      { path: 'r2.ts', content: lines(300, 'r2') },
    ];
    const full = buildReviewContext({ pr, files, related, budgetTokens: 1_000_000 });
    const noRelated = buildReviewContext({ pr, files, related: [], budgetTokens: 1_000_000 });

    const firstCut = buildReviewContext({ pr, files, related, budgetTokens: full.estimatedTokens - 10 });
    expect(firstCut.related).toEqual(['r1.ts']);

    const shrunk = buildReviewContext({ pr, files, related, budgetTokens: noRelated.estimatedTokens - 10 });
    expect(shrunk.related).toEqual([]);
    expect(shrunk.files.map((f) => f.mode)).toEqual(['full', 'full', 'excerpt']);

    const lowestFirst = buildReviewContext({ pr, files, related, budgetTokens: 900 });
    expect(lowestFirst.files.map((f) => f.mode)).toEqual(['excerpt', 'patch', 'patch']);

    const patchesOnly = buildReviewContext({ pr, files, related, budgetTokens: 700 });
    expect(patchesOnly.files.map((f) => f.mode)).toEqual(['patch', 'patch', 'patch']);
    expect(patchesOnly.droppedFiles).toEqual([]);

    const dropped = buildReviewContext({ pr, files, related, budgetTokens: 120 });
    expect(dropped.files.map((f) => f.path)).toEqual(['src/api/a.ts']);
    expect(dropped.droppedFiles).toEqual(['test/c.test.ts', 'src/b.ts']);
  });

  it('keeps only the first hunks of the last file when even its patch is too large', () => {
    const hunk = (start: number) => `@@ -${start},1 +${start},1 @@\n-a\n+${'x'.repeat(600)}`;
    const big: ChangedFile = {
      path: 'src/big.ts',
      status: 'modified',
      patch: [hunk(1), hunk(10), hunk(20)].join('\n'),
      additions: 3,
      deletions: 3,
    };
    const ctx = buildReviewContext({ pr, files: [big], related: [], budgetTokens: 380 });
    expect(ctx.files).toEqual([{ path: 'src/big.ts', mode: 'patch', truncated: true }]);
    expect(ctx.text).toContain('truncated="true"');
    expect(ctx.text).not.toContain('@@ -20,1');
  });
});

describe('content-based filtering', () => {
  const base = { status: 'modified' as const, additions: 1, deletions: 0, patch: '@@ -1 +1 @@\n+x' };

  it('skips generated files by header, minified files and binary content', () => {
    const generated = {
      ...base,
      path: 'src/api.ts',
      newContent: '// Code generated by openapi. DO NOT EDIT.\nexport {}',
    };
    const prismaGen = { ...base, path: 'src/a.ts', newContent: '/* @generated */\nexport {}' };
    const minified = { ...base, path: 'public/app.js', newContent: `var a=1;${'b=2;'.repeat(800)}` };
    const binary = { ...base, path: 'data.bin2', newContent: 'ab\u0000cd' };
    const normal = {
      ...base,
      path: 'src/ok.ts',
      newContent: '// Do not edit without updating the docs.\nexport {}',
    };
    expect(looksGenerated(generated)).toBe(true);
    expect(looksGenerated(prismaGen)).toBe(true);
    expect(looksGenerated(normal)).toBe(false);
    expect(looksMinified(minified)).toBe(true);
    expect(looksMinified(normal)).toBe(false);
    const { reviewable, skipped } = filterFiles([generated, prismaGen, minified, binary, normal]);
    expect(reviewable.map((f) => f.path)).toEqual(['src/ok.ts']);
    expect(skipped).toEqual([
      { path: 'src/api.ts', reason: 'ignored' },
      { path: 'src/a.ts', reason: 'ignored' },
      { path: 'public/app.js', reason: 'ignored' },
      { path: 'data.bin2', reason: 'binary' },
    ]);
  });
});
